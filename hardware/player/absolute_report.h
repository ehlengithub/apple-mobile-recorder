#pragma once
#include <array>
#include <stdint.h>

// Same absolute mouse layout/range as the accepted USB version. Report ID 1
// is carried by the BLE Report Reference descriptor, not in the value bytes.
constexpr uint8_t BLE_ABSOLUTE_MAP[] = {
  0x05,0x01, 0x09,0x02, 0xA1,0x01, 0x85,0x01,
  0x09,0x01, 0xA1,0x00,
  0x05,0x09, 0x19,0x01, 0x29,0x05, 0x15,0x00, 0x25,0x01,
  0x95,0x05, 0x75,0x01, 0x81,0x02,
  0x95,0x01, 0x75,0x03, 0x81,0x01,
  0x05,0x01, 0x09,0x30, 0x09,0x31,
  0x15,0x00, 0x26,0xFF,0x7F, 0x75,0x10, 0x95,0x02, 0x81,0x02,
  0x09,0x38, 0x15,0x81, 0x25,0x7F, 0x95,0x01, 0x75,0x08, 0x81,0x06,
  // iOS expects AC Pan inside its own Logical collection over BLE.
  0xA1,0x02, 0x05,0x0C, 0x0A,0x38,0x02, 0x15,0x81, 0x25,0x7F,
  0x95,0x01, 0x75,0x08, 0x81,0x06, 0xC0,0xC0,0xC0
};

inline std::array<uint8_t, 7> absoluteReport(uint16_t x, uint16_t y, uint8_t buttons) {
  return {buttons, uint8_t(x), uint8_t(x >> 8), uint8_t(y), uint8_t(y >> 8), 0, 0};
}
